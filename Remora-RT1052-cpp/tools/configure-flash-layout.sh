#!/usr/bin/env bash

set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
project_dir="$(cd "$script_dir/.." && pwd)"
defaults_file="$project_dir/config/flash-layout.env"
header_file="$project_dir/board/flash_layout.h"
cproject_file="$project_dir/.cproject"

read_default() {
    local name="$1"
    local value
    value="$(sed -n "s/^${name}=//p" "$defaults_file")"
    if [[ -z "$value" ]]; then
        echo "Missing $name in $defaults_file" >&2
        exit 1
    fi
    printf '%s' "$value"
}

parse_size() {
    local name="$1"
    local value="$2"
    if [[ ! "$value" =~ ^(0[xX][0-9a-fA-F]+|[0-9]+)$ ]]; then
        echo "$name must be a hexadecimal or decimal byte count: $value" >&2
        exit 1
    fi
    printf '%u' "$((value))"
}

default_flash_size="$(read_default NVEM_FLASH_SIZE_BYTES)"
default_json_region_size="$(read_default NVEM_JSON_REGION_SIZE_BYTES)"

flash_size="$(parse_size NVEM_FLASH_SIZE_BYTES "${NVEM_FLASH_SIZE_BYTES:-$default_flash_size}")"
json_region_size="$(parse_size NVEM_JSON_REGION_SIZE_BYTES "${NVEM_JSON_REGION_SIZE_BYTES:-$default_json_region_size}")"

sector_size=$((0x1000))
metadata_size=512
tftp_block_size=512
json_reserved_size=$((2 * json_region_size))

if ((flash_size % sector_size != 0)); then
    echo "NVEM_FLASH_SIZE_BYTES must be aligned to $sector_size-byte sectors" >&2
    exit 1
fi
if ((json_region_size < metadata_size || json_region_size % sector_size != 0)); then
    echo "NVEM_JSON_REGION_SIZE_BYTES must be at least $metadata_size bytes and sector-aligned" >&2
    exit 1
fi
if ((json_region_size % tftp_block_size != 0)); then
    echo "NVEM_JSON_REGION_SIZE_BYTES must contain whole $tftp_block_size-byte TFTP blocks" >&2
    exit 1
fi
if ((flash_size <= json_reserved_size)); then
    echo "Flash must be larger than the two reserved JSON regions" >&2
    exit 1
fi

application_size=$((flash_size - json_reserved_size))
flash_hex="$(printf '0x%x' "$flash_size")"
json_hex="$(printf '0x%x' "$json_region_size")"
application_hex="$(printf '0x%x' "$application_size")"

header_tmp="$(mktemp "${TMPDIR:-/tmp}/flash-layout-header.XXXXXX")"
cproject_tmp="$(mktemp "${TMPDIR:-/tmp}/flash-layout-cproject.XXXXXX")"
trap 'rm -f "$header_tmp" "$cproject_tmp"' EXIT

cat >"$header_tmp" <<EOF
/* Auto-generated by tools/configure-flash-layout.sh. Do not edit directly. */
#ifndef FLASH_LAYOUT_H_
#define FLASH_LAYOUT_H_

#define BOARD_FLASH_SIZE             (${flash_hex}U)
#define BOARD_FLASH_SECTOR_SIZE      (0x1000U)
#define BOARD_JSON_REGION_SIZE       (${json_hex}U)
#define BOARD_JSON_RESERVED_SIZE     (2U * BOARD_JSON_REGION_SIZE)
#define BOARD_APPLICATION_FLASH_SIZE (BOARD_FLASH_SIZE - BOARD_JSON_RESERVED_SIZE)

#endif /* FLASH_LAYOUT_H_ */
EOF

if ! cmp -s "$header_tmp" "$header_file"; then
    cp "$header_tmp" "$header_file"
fi

match_count="$(grep -c 'id="BOARD_FLASH" location="0x60000000" size="0x[0-9A-Fa-f]*"' "$cproject_file" || true)"
if [[ "$match_count" != "1" ]]; then
    echo "Expected exactly one BOARD_FLASH memory entry in $cproject_file; found $match_count" >&2
    exit 1
fi

sed -E "s|(id=\"BOARD_FLASH\" location=\"0x60000000\" size=\")0x[0-9A-Fa-f]+|\\1${application_hex}|" \
    "$cproject_file" >"$cproject_tmp"
if ! cmp -s "$cproject_tmp" "$cproject_file"; then
    cp "$cproject_tmp" "$cproject_file"
fi

printf 'Physical flash:   %s bytes (%s)\n' "$flash_size" "$flash_hex"
printf 'Application/XIP:  %s bytes (%s)\n' "$application_size" "$application_hex"
printf 'JSON upload:      %s bytes (%s)\n' "$json_region_size" "$json_hex"
printf 'JSON storage:     %s bytes (%s)\n' "$json_region_size" "$json_hex"
